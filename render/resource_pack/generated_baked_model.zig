pub fn bake(
    gpa: std.mem.Allocator,
    textures: std.array_hash_map.String(zigimg.Image),
    texture_handles: [5]?Renderer.TextureHandle,
    x_rotation: StateToModelMap.ModelVariant.Angle,
    y_rotation: StateToModelMap.ModelVariant.Angle,
    uvlock: bool,
) !BakedModel {
    if (uvlock) std.log.warn("autogenerated item models do not support uvlock, ignoring!", .{});

    var faces: std.ArrayList(BakedModel.Face) = .empty;
    for (texture_handles) |maybe_texture_handle| {
        const texture_handle = maybe_texture_handle orelse break;
        const image: zigimg.Image = textures.entries.items(.value)[@backingInt(texture_handle)];
        {
            const ir: BakedModel.IntermediateFace = .{
                .facing = .south,
                .xy = .{ .splat(0), .splat(16) },
                .z = 7.5,
                .geometry_rotation = null,
                .uv = .{ .{ .x = 0, .y = 0 }, .{ .x = 16, .y = 16 } },
                .cullface = null,
                .texture_rotation = .@"0",
                .texture = texture_handle,
            };
            try faces.append(gpa, ir.bake());
        }
        {
            const ir: BakedModel.IntermediateFace = .{
                .facing = .north,
                .xy = .{ .splat(0), .splat(16) },
                .z = 7.5,
                .geometry_rotation = null,
                .uv = .{ .{ .x = 16, .y = 0 }, .{ .x = 0, .y = 16 } },
                .cullface = null,
                .texture_rotation = .@"0",
                .texture = texture_handle,
            };
            try faces.append(gpa, ir.bake());
        }
        // convert everything to rgba32
        var maybe_owned_storage: ?zigimg.color.PixelStorage = null;
        defer if (maybe_owned_storage) |owned_storage| owned_storage.deinit(gpa);

        if (image.pixels != .rgba32) {
            maybe_owned_storage = zigimg.PixelFormatConverter.convert(gpa, &image.pixels, .rgba32) catch {
                std.log.scoped(.resource_pack).warn("could not convert image to rgba32, leaving it blank", .{});
                continue;
            };
        }

        const pixels = switch (image.pixels) {
            .rgba32 => |pixels| pixels,
            else => maybe_owned_storage.?.rgba32,
        };

        for (0..image.width) |x| {
            for (0..image.height) |y| {
                if (pixels[y * image.width + x].a == 0) continue;
                const left_border = (x == 0) or (pixels[y * image.width + x - 1].a == 0);
                if (left_border) {
                    const ir: BakedModel.IntermediateFace = .{
                        .facing = .west,
                        .xy = .{ .{ .x = 7.5, .y = @floatFromInt(15 - y) }, .{ .x = 8.5, .y = @floatFromInt(16 - y) } },
                        .z = @floatFromInt(x),
                        .geometry_rotation = null,
                        .uv = .{ .{ .x = @floatFromInt(x), .y = @floatFromInt(y) }, .{ .x = @floatFromInt(x + 1), .y = @floatFromInt(y + 1) } },
                        .cullface = null,
                        .texture_rotation = .@"0",
                        .texture = texture_handle,
                    };
                    try faces.append(gpa, ir.bake());
                }

                const right_border = (x == image.width - 1) or (pixels[y * image.width + x + 1].a == 0);
                if (right_border) {
                    const ir: BakedModel.IntermediateFace = .{
                        .facing = .east,
                        .xy = .{ .{ .x = 7.5, .y = @floatFromInt(15 - y) }, .{ .x = 8.5, .y = @floatFromInt(16 - y) } },
                        .z = @floatFromInt(15 - x),
                        .geometry_rotation = null,
                        .uv = .{ .{ .x = @floatFromInt(x), .y = @floatFromInt(y) }, .{ .x = @floatFromInt(x + 1), .y = @floatFromInt(y + 1) } },
                        .cullface = null,
                        .texture_rotation = .@"0",
                        .texture = texture_handle,
                    };
                    try faces.append(gpa, ir.bake());
                }

                const up_border = (y == 0) or (pixels[(y - 1) * image.width + x].a == 0);
                if (up_border) {
                    const ir: BakedModel.IntermediateFace = .{
                        .facing = .up,
                        .xy = .{ .{ .x = @floatFromInt(x), .y = 7.5 }, .{ .x = @floatFromInt(x + 1), .y = 8.5 } },
                        .z = @floatFromInt(y),
                        .geometry_rotation = null,
                        .uv = .{ .{ .x = @floatFromInt(x), .y = @floatFromInt(y) }, .{ .x = @floatFromInt(x + 1), .y = @floatFromInt(y + 1) } },
                        .cullface = null,
                        .texture_rotation = .@"0",
                        .texture = texture_handle,
                    };
                    try faces.append(gpa, ir.bake());
                }

                const down_border = (y == image.height - 1) or (pixels[(y + 1) * image.width + x].a == 0);
                if (down_border) {
                    const ir: BakedModel.IntermediateFace = .{
                        .facing = .down,
                        .xy = .{ .{ .x = @floatFromInt(x), .y = 7.5 }, .{ .x = @floatFromInt(x + 1), .y = 8.5 } },
                        .z = @floatFromInt(15 - y),
                        .geometry_rotation = null,
                        .uv = .{ .{ .x = @floatFromInt(x), .y = @floatFromInt(y) }, .{ .x = @floatFromInt(x + 1), .y = @floatFromInt(y + 1) } },
                        .cullface = null,
                        .texture_rotation = .@"0",
                        .texture = texture_handle,
                    };
                    try faces.append(gpa, ir.bake());
                }
            }
        }
    }
    _ = x_rotation;
    _ = y_rotation;

    return .{ .faces = try faces.toOwnedSlice(gpa) };
}

const std = @import("std");

const render = @import("render");
const zigimg = @import("zigimg");

const BakedModel = @import("BakedModel.zig");
const StateToModelMap = @import("StateToModelMap.zig");

const Renderer = render.Renderer;
